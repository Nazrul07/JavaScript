// Regular function
function square_rg(x){
    return x * x;
}

// Expression function
const square_ex = function(x){
    return x * x;
}

// Arrow function
const square_ar = (x) => {
    return x * x;
} 

// Arrow function - shorter form
const square_ar_shorter = (x) => x * x;

// No parameters - shorter form
const greet = () => "Hello!";

// Multiple parameters - shorter form
const multiply = (a, b) => a * b;